/**
 * SIKIŞTIRILMIŞ AKTARIM (UFP) — 211 MB'lık dosya U1'e WiFi üzerinden üç denemede de gitmedi
 * (8 Kas 2026). Dosya artık zip olarak gidiyor, yazıcı aynı adla `.gcode`'a açıyor.
 *
 * Burada iki şey doğrulanır:
 *   1. Paket, Moonraker'ın (Python `zipfile`) okuduğu biçimde: tek kayıt, ad TAM OLARAK
 *      `/3D/model.gcode`, içerik bayt bayt aynı, CRC doğru — çok parçalı (4 MB üstü) dosyada da.
 *   2. Uçtan uca akış (sahte Moonraker): U1'e `.ufp` gider, açılan dosya özgünle aynıdır, baskı
 *      `.gcode` adıyla başlar; yazıcı paketi reddederse ham dosya gider; Snapmaker dışında değişiklik yok.
 */
import http from "node:http";
import type { AddressInfo } from "node:net";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { unzipSync } from "fflate";

import { crc32, ufpAdi, ufpPaketle, ufpUygunMu, UFP_MODEL_YOLU } from "./ufp";
import {
  clearMoonrakerCaps, clearMoonrakerPort, moonrakerUploadAndPrint, ufpBeklenenYerde, ufpReddedildi,
} from "./moonraker";

/** Gerçekçi G-code: sayılar değişen satırlar (sıkışma oranı gerçek dosyalara yakın kalsın). */
function ornekGcode(baytHedef: number): Buffer {
  const satirlar: string[] = ["; generated by OrcaSlicer\n"];
  let toplam = satirlar[0].length;
  for (let i = 0; toplam < baytHedef; i++) {
    const s = `G1 X${((i * 0.37) % 250).toFixed(3)} Y${((i * 0.91) % 250).toFixed(3)} E${(i % 97) / 1000}\n`;
    satirlar.push(s);
    toplam += s.length;
  }
  return Buffer.from(satirlar.join(""), "utf8");
}

describe("UFP paketi", () => {
  it("tek kayıt, adı tam /3D/model.gcode, içerik bayt bayt aynı", async () => {
    const gcode = ornekGcode(200_000);
    const zip = await ufpPaketle(gcode);
    const acilan = unzipSync(new Uint8Array(zip));
    expect(Object.keys(acilan)).toEqual([UFP_MODEL_YOLU]);
    expect(Buffer.from(acilan[UFP_MODEL_YOLU]).equals(gcode)).toBe(true);
    expect(zip.length).toBeLessThan(gcode.length / 2);
  });

  it("4 MB'ı aşan dosya parça parça sıkışır, yine aynı açılır; yüzde artarak 100'e varır", async () => {
    const gcode = ornekGcode(9 * 1024 * 1024 + 123);
    const yuzdeler: number[] = [];
    const zip = await ufpPaketle(gcode, (p) => yuzdeler.push(p));
    const acilan = unzipSync(new Uint8Array(zip));
    expect(Buffer.from(acilan[UFP_MODEL_YOLU]).equals(gcode)).toBe(true);
    expect(yuzdeler.length).toBeGreaterThan(2);
    expect(yuzdeler.at(-1)).toBe(100);
    for (let i = 1; i < yuzdeler.length; i++) expect(yuzdeler[i]).toBeGreaterThanOrEqual(yuzdeler[i - 1]);
  });

  it("zip başlıkları tutarlı: yerel başlık ve merkez dizin aynı CRC'yi ve boyutları taşır", async () => {
    const gcode = ornekGcode(50_000);
    const zip = await ufpPaketle(gcode);
    expect(zip.readUInt32LE(0)).toBe(0x04034b50);
    const crc = zip.readUInt32LE(14);
    expect(crc).toBe(crc32(gcode));
    expect(zip.readUInt32LE(22)).toBe(gcode.length);
    const sonKonum = zip.length - 22;
    expect(zip.readUInt32LE(sonKonum)).toBe(0x06054b50);
    const merkezKonum = zip.readUInt32LE(sonKonum + 16);
    expect(zip.readUInt32LE(merkezKonum)).toBe(0x02014b50);
    expect(zip.readUInt32LE(merkezKonum + 16)).toBe(crc);
    expect(zip.readUInt32LE(merkezKonum + 24)).toBe(gcode.length);
  });

  it("CRC-32 bilinen değeri verir ve parça parça hesap tek seferle aynıdır", () => {
    expect(crc32(Buffer.from("123456789"))).toBe(0xcbf43926);
    const veri = ornekGcode(100_000);
    const parcali = crc32(veri.subarray(40_000), crc32(veri.subarray(0, 40_000)));
    expect(parcali).toBe(crc32(veri));
  });

  it("yalnız .gcode uzantısı uygundur (yazıcı çıktıyı hep .gcode adlandırır)", () => {
    expect(ufpUygunMu("Sauron-abc.gcode", 1000)).toBe(true);
    expect(ufpUygunMu("parca.gco", 1000)).toBe(false);
    expect(ufpUygunMu("parca.GCODE", 1000)).toBe(false);
    expect(ufpUygunMu("parca.3mf", 1000)).toBe(false);
    expect(ufpUygunMu("bos.gcode", 0)).toBe(false);
    expect(ufpAdi("Sauron Pelerin-1a2b3c.gcode")).toBe("Sauron Pelerin-1a2b3c.ufp");
  });
});

describe("yazıcının yanıtı", () => {
  it("paket ağ dışı bir sebeple reddedildiyse ham dosyaya dönülür; ağ kopması bu sayılmaz", () => {
    expect(ufpReddedildi(new Error("Yükleme başarısız (HTTP 400) bad ext"))).toBe(true);
    expect(ufpReddedildi(new Error("Yükleme başarısız (HTTP 500)"))).toBe(true);
    expect(ufpReddedildi(new Error("Yazıcıyla bağlantı aktarım sırasında koptu."))).toBe(false);
    expect(ufpReddedildi(new Error("Yazıcıda yer yok — eski baskı dosyalarını silip tekrar dene."))).toBe(false);
  });

  it("açılan dosyanın adı ve boyutu doğrulanır", () => {
    const ok = { item: { path: "A-1.gcode", size: 500, root: "gcodes" } };
    expect(ufpBeklenenYerde(ok, "A-1.gcode", 500)).toBe(true);
    expect(ufpBeklenenYerde({ item: { path: "A-1.ufp", size: 120 } }, "A-1.gcode", 500)).toBe(false);
    expect(ufpBeklenenYerde({ item: { path: "A-1.gcode", size: 499 } }, "A-1.gcode", 500)).toBe(false);
    expect(ufpBeklenenYerde({}, "A-1.gcode", 500)).toBe(true); // yanıt söylemiyorsa güven
    expect(ufpBeklenenYerde(null, "A-1.gcode", 500)).toBe(true);
  });
});

/* ── Uçtan uca: sahte Moonraker ───────────────────────────────────────────── */

interface Yukleme { ad: string; bayt: number; print: string }
let sunucu: http.Server;
let port = 0;
let yuklemeler: Yukleme[] = [];
let kart = new Map<string, Buffer>();
let ufpReddet = false;
let scriptler: string[] = [];

function multipartAyikla(govde: Buffer, sinir: string) {
  const metin = govde.toString("latin1");
  const alan = (ad: string) => {
    const m = new RegExp(`name="${ad}"\\r\\n\\r\\n([^\\r]*)`).exec(metin);
    return m ? m[1] : "";
  };
  const dosyaAdi = /filename="([^"]+)"/.exec(metin)?.[1] ?? "";
  const bas = metin.indexOf("\r\n\r\n", metin.indexOf('name="file"')) + 4;
  const son = metin.lastIndexOf(`\r\n--${sinir}--`);
  return { dosyaAdi, print: alan("print"), dosya: govde.subarray(bas, son) };
}

beforeEach(async () => {
  yuklemeler = [];
  kart = new Map();
  ufpReddet = false;
  scriptler = [];
  sunucu = http.createServer((req, res) => {
    const parcalar: Buffer[] = [];
    req.on("data", (c: Buffer) => parcalar.push(c));
    req.on("end", () => {
      if (req.url !== "/server/files/upload") { res.statusCode = 404; res.end(); return; }
      const sinir = /boundary=(.+)$/.exec(req.headers["content-type"] ?? "")?.[1] ?? "";
      const { dosyaAdi, print, dosya } = multipartAyikla(Buffer.concat(parcalar), sinir);
      yuklemeler.push({ ad: dosyaAdi, bayt: dosya.length, print });
      let kayitAdi = dosyaAdi;
      let icerik = Buffer.from(dosya);
      if (dosyaAdi.endsWith(".ufp")) {
        if (ufpReddet) { res.statusCode = 400; res.end('{"error":"bad ext"}'); return; }
        // Moonraker gibi: /3D/model.gcode'u aynı adla .gcode olarak çıkar, zip'i at.
        icerik = Buffer.from(unzipSync(new Uint8Array(dosya))[UFP_MODEL_YOLU]);
        kayitAdi = dosyaAdi.replace(/\.ufp$/, ".gcode");
      }
      kart.set(kayitAdi, icerik);
      res.setHeader("Content-Type", "application/json");
      res.end(JSON.stringify({
        result: {
          action: "create_file",
          item: { path: kayitAdi, size: icerik.length, root: "gcodes" },
          print_started: print === "true",
        },
      }));
    });
  });
  await new Promise<void>((r) => sunucu.listen(0, "127.0.0.1", () => r()));
  port = (sunucu.address() as AddressInfo).port;

  clearMoonrakerPort();
  clearMoonrakerCaps();
  // JSON uçları (durum / meta / komut) fetch'ten gider; yükleme gerçek sahte sunucuya.
  vi.stubGlobal("fetch", vi.fn(async (url: string, init?: RequestInit) => {
    const u = new URL(String(url));
    const json = (body: unknown) => ({
      ok: true, status: 200, json: async () => body, text: async () => JSON.stringify(body),
    }) as unknown as Response;
    if (u.pathname === "/printer/objects/query") {
      return json({ result: { status: {
        print_stats: { state: "standby", filename: null, print_duration: 0, info: {} },
        virtual_sdcard: { progress: 0 },
        extruder: { temperature: 25, target: 0 },
        heater_bed: { temperature: 24, target: 0 },
      } } });
    }
    if (u.pathname === "/server/files/metadata") return json({ result: { filament_type: "PLA" } });
    if (u.pathname === "/printer/gcode/script") {
      const govde = typeof init?.body === "string" ? (JSON.parse(init.body) as { script?: string }) : {};
      scriptler.push(govde.script ?? u.searchParams.get("script") ?? "");
      return json({ result: "ok" });
    }
    return json({ result: {} });
  }));
});

afterEach(async () => {
  vi.unstubAllGlobals();
  await new Promise<void>((r) => sunucu.close(() => r()));
});

describe("U1'e aktarım (sahte Moonraker)", () => {
  it("dosya sıkıştırılarak gider, yazıcıda bayt bayt aynı açılır, baskı .gcode adıyla başlar", async () => {
    const gcode = ornekGcode(2 * 1024 * 1024);
    const sikistirma: number[] = [];
    const yukleme: number[] = [];
    await moonrakerUploadAndPrint("127.0.0.1", port, gcode, "Sauron Pelerin-1a2b3c.gcode", {
      brand: "Snapmaker",
      onPack: (p) => sikistirma.push(p),
      onProgress: (p) => yukleme.push(p),
    });
    expect(yuklemeler).toHaveLength(1);
    expect(yuklemeler[0].ad).toBe("Sauron Pelerin-1a2b3c.ufp");
    expect(yuklemeler[0].print).toBe("false");
    expect(yuklemeler[0].bayt).toBeLessThan(gcode.length / 2); // ağdan giden veri yarıdan az
    expect(kart.get("Sauron Pelerin-1a2b3c.gcode")?.equals(gcode)).toBe(true);
    expect(sikistirma.at(-1)).toBe(100);
    expect(yukleme.length).toBeGreaterThan(0);
    expect(scriptler.join("\n")).toContain("Sauron Pelerin-1a2b3c.gcode");
  });

  it("yazıcı paketi reddederse aynı istek içinde ham dosya gider ve baskı yine başlar", async () => {
    ufpReddet = true;
    const gcode = ornekGcode(300_000);
    await moonrakerUploadAndPrint("127.0.0.1", port, gcode, "Parca-9f.gcode", { brand: "Snapmaker" });
    expect(yuklemeler.map((y) => y.ad)).toEqual(["Parca-9f.ufp", "Parca-9f.gcode"]);
    expect(kart.get("Parca-9f.gcode")?.equals(gcode)).toBe(true);
    expect(scriptler.join("\n")).toContain("Parca-9f.gcode");
  });

  it("Snapmaker dışı Moonraker yazıcısında dosya eskisi gibi ham ve tek seferde gider", async () => {
    const gcode = ornekGcode(300_000);
    await moonrakerUploadAndPrint("127.0.0.1", port, gcode, "Parca-9f.gcode", {});
    expect(yuklemeler).toHaveLength(1);
    expect(yuklemeler[0]).toMatchObject({ ad: "Parca-9f.gcode", print: "true", bayt: gcode.length });
  });

  it("MLHUB_UFP=0 sıkıştırmayı kapatır", async () => {
    vi.stubEnv("MLHUB_UFP", "0");
    try {
      const gcode = ornekGcode(300_000);
      await moonrakerUploadAndPrint("127.0.0.1", port, gcode, "Parca-9f.gcode", { brand: "Snapmaker" });
      expect(yuklemeler.map((y) => y.ad)).toEqual(["Parca-9f.gcode"]);
    } finally {
      vi.unstubAllEnvs();
    }
  });
});
